#!/usr/bin/env python3
"""Generate a private loopback HTTP/SOCKS → Trojan-over-WSS sing-box config."""
import argparse
import getpass
import ipaddress
import json
import os
from pathlib import Path
import re
from common import read_env, valid_path, write_private


def normalize_host(host):
    if '://' in host or any(c in host for c in '/?#@ \\'):
        raise ValueError('--server must be a hostname or IP, not a URL. Use --port separately.')
    try:
        return str(ipaddress.ip_address(host))
    except ValueError:
        pass
    if len(host) > 253 or not re.fullmatch(r'[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?', host):
        raise ValueError('Invalid server hostname.')
    if any(not p or len(p) > 63 or p.startswith('-') or p.endswith('-') for p in host.split('.')):
        raise ValueError('Invalid server hostname label.')
    return host.lower()


def make_config(host, password, ws_path='/tunnel', port=443, listen_port=1080, plaintext=False):
    host = normalize_host(host)
    valid_path(ws_path)
    if not 1 <= port <= 65535 or not 1024 <= listen_port <= 65535:
        raise ValueError('Invalid port.')
    if len(password) < 24 or len(password) > 256 or any(not 33 <= ord(c) <= 126 for c in password):
        raise ValueError('Password must contain 24-256 printable non-space ASCII characters.')
    if plaintext and host not in ('127.0.0.1', '::1', 'localhost'):
        raise ValueError('Plaintext WebSocket is permitted only for a local loopback test.')
    outbound = {
        'type': 'trojan', 'tag': 'render-trojan', 'server': host, 'server_port': port,
        'password': password, 'network': 'tcp',
        'transport': {'type': 'ws', 'path': ws_path},
    }
    if not plaintext:
        outbound['tls'] = {'enabled': True, 'server_name': host, 'insecure': False, 'alpn': ['http/1.1']}
    return {
        'log': {'level': 'warn', 'timestamp': True},
        'dns': {'servers': [{'type': 'local', 'tag': 'bootstrap'}], 'final': 'bootstrap'},
        'inbounds': [{'type': 'mixed', 'tag': 'local-proxy', 'listen': '127.0.0.1', 'listen_port': listen_port}],
        'outbounds': [outbound],
        'route': {'final': 'render-trojan', 'default_domain_resolver': {'server': 'bootstrap', 'strategy': 'ipv4_only'}},
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--server', required=True, help='e.g. your-service.onrender.com (no scheme)')
    parser.add_argument('--port', type=int, help='Default 443, or 10000 with --local-plaintext')
    parser.add_argument('--listen-port', type=int, default=1080)
    parser.add_argument('--ws-path', help='Must match WS_PATH on the server')
    secret_source = parser.add_mutually_exclusive_group()
    secret_source.add_argument('--env-file', type=Path, help='Read password and WS_PATH from a private local .env')
    secret_source.add_argument('--users-file', type=Path, help='Operator-only private JSON generated by users.py')
    parser.add_argument('--user', help='User name to select from --users-file')
    parser.add_argument('--password-env', default='TROJAN_PASSWORD', help='Name of a password environment variable, never the password itself')
    parser.add_argument('--local-plaintext', action='store_true', help='ONLY for a loopback Docker test; TLS is never disabled for a remote host')
    parser.add_argument('--output', type=Path, default=Path('clients/sing-box-client.json'))
    args = parser.parse_args()
    try:
        values = read_env(args.env_file) if args.env_file else {}
        if args.users_file:
            from users import select_password
            password = select_password(args.users_file, args.user)
        else:
            if args.user:
                raise ValueError('--user requires --users-file.')
            password = values.get('TROJAN_PASSWORD') or os.getenv(args.password_env) or getpass.getpass('Trojan password (hidden): ')
        ws_path = args.ws_path or values.get('WS_PATH', '/tunnel')
        conf = make_config(args.server, password, ws_path, args.port or (10000 if args.local_plaintext else 443), args.listen_port, args.local_plaintext)
        write_private(args.output, json.dumps(conf, ensure_ascii=False, indent=2) + '\n')
    except (ValueError, OSError) as error:
        parser.exit(1, f'Cannot create client config: {error}\n')
    print(f'Private client config created: {args.output}; do not commit, publish, or share it.')
    print(f'Run: sing-box run -c {args.output}')
    print(f'HTTP/SOCKS proxy: 127.0.0.1:{args.listen_port}. Other applications are NOT automatically tunneled.')
